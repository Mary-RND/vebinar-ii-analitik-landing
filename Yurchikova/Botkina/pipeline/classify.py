# подгруппы внутри ОКПД2 32.50.13: группа слишком широкая, чтобы быть
# единственной категорией (в 2025 году её формируют роботизированные
# инструменты, офтальмологические наборы и катетеры)
SUBGROUPS_325013: tuple[tuple[tuple[str, ...], str], ...] = (
    (("роботизированн", "da vinci", "да винчи"), "Инструменты для роботизированной хирургии"),
    (("офтальмолог", "витректом", "факоэмульсификац"), "Офтальмологические наборы и инструменты"),
    (("катетер", "дренаж", "троакар"), "Катетеры, дренажи и троакары"),
)


def _startswith_any(code: str | None, prefixes: tuple[str, ...]) -> bool:
    return bool(code) and any(code.startswith(p) for p in prefixes)


def classify(
    okpd2: str | None,
    ktru: str | None = None,
    name: str | None = None,
) -> tuple[str, str, str, str | None]:
    """Вернуть (вид, группа L2, scope, причина).

    scope: main | borderline | excluded.
    """
    low = (name or "").lower()

    # 1. услуги и работы
    if any(m in low for m in SERVICE_MARKERS) or _startswith_any(
        okpd2, ("33.", "43.", "45.", "49.", "56.", "62.", "63.", "71.", "80.", "81.", "85.", "86.", "96.01", "38.12")
    ):
        for prefix, bucket, kind in RULES:
            if kind == "service" and (okpd2 or "").startswith(prefix):
                return kind, bucket, "excluded", "услуга/работа"
        return "service", "Услуги и работы", "excluded", "услуга/работа"

    # 2. явные нецелевые маркеры
    if any(m in low for m in HOUSEHOLD_MARKERS):
        for prefix, bucket, kind in RULES:
            if kind == "household" and (okpd2 or "").startswith(prefix):
                return kind, bucket, "excluded", "хозяйственные расходы"
        return "household", "Хозяйственные расходы", "excluded", "хозяйственные расходы"

    # 3. имплантаты
    if any(m in low for m in IMPLANT_MARKERS):
        return "implant", "Имплантаты, стенты и эндопротезы", "main", "маркер имплантата"

    # 4. правила по ОКПД2/КТРУ
    for code in (okpd2, ktru):
        if not code:
            continue
        if code.startswith("32.50.13"):
            for markers, bucket in SUBGROUPS_325013:
                if any(m in low for m in markers):
                    return "consumable", bucket, "main", "подгруппа 32.50.13"
        for prefix, bucket, kind in RULES:
            if code.startswith(prefix):
                scope = "excluded" if kind in EXCLUDED_KINDS else (
                    "borderline" if kind in BORDERLINE_KINDS else "main"
                )
                reason = {
                    "drug": "фармация",
                    "household": "хозяйственные расходы",
                    "service": "услуга/работа",
                }.get(kind)
                return kind, bucket, scope, reason

    # 5. лабораторные маркеры (когда ОКПД2 не указан)
    if any(m in low for m in LAB_MARKERS):
        return "lab", "Реагенты диагностические (ИВД)", "borderline", "маркер реагента"

    # 6. расходные материалы по маркерам (когда ОКПД2 не указан)
    if any(m in low for m in CONSUMABLE_MARKERS):
        return "consumable", "Расходные материалы прочие", "main", "маркер расходного материала"

    # 7. оборудование по маркерам
    if any(m in low for m in EQUIPMENT_MARKERS):
        return "equipment", "Медицинское оборудование", "main", "маркер оборудования"

    # 8. остаток
    return "other", "Вне классификации", "excluded", "не классифицировано"
