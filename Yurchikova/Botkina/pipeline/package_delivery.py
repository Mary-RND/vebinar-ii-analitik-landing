"""Сборка пакета передачи заказчику: все артефакты + опись в ZIP."""
from __future__ import annotations

import zipfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "output"
ZIP_PATH = OUT / "Анализ_закупок_МНКЦ_им_С.П._Боткина_2025.zip"

FILES = [
    ("REPORT_Botkin_2025.pdf", "Аналитический отчёт (PDF)"),
    ("REPORT_Botkin_2025.docx", "Аналитический отчёт (DOCX)"),
    ("dashboard.html", "Интерактивный дашборд (один HTML-файл, работает офлайн)"),
    ("ММНКЦ_Боткина_2025_аналитика.xlsx", "Рабочая книга Excel с таблицами отчёта (14 листов)"),
    ("Реестр_позиций_Боткина_2025.xlsx", "Реестр позиций (XLSX)"),
    ("Реестр_позиций_Боткина_2025.csv", "Реестр позиций (CSV, UTF-8 с BOM, разделитель «;»)"),
    ("Методика_и_паспорт_данных.pdf", "Методика и паспорт данных (PDF)"),
    ("Методика_и_паспорт_данных.docx", "Методика и паспорт данных (DOCX)"),
    ("Инструкция_по_работе_с_дашбордом.pdf", "Инструкция по работе с дашбордом (PDF)"),
    ("Инструкция_по_работе_с_дашбордом.docx", "Инструкция по работе с дашбордом (DOCX)"),
]

README = """СОСТАВ ПЕРЕДАЧИ
Анализ закупок МНКЦ им. С.П. Боткина за 2025 год
Дата выгрузки данных: 2026-10-22. Период: 01.01.2025 — 31.12.2025.
Источники: ЕИС, реестр контрактов 44-ФЗ и реестр договоров 223-ФЗ.

ФАЙЛЫ
{lines}

КАК НАЧАТЬ РАБОТУ
1. Отчёт — REPORT_Botkin_2025.pdf (58 страниц, A4, с оглавлением и подписями к рисункам).
2. Дашборд — dashboard.html: открыть двойным щелчком в Chrome, Edge или Firefox.
   Интернет, сервер и установка не нужны: все данные и библиотеки встроены в файл.
   Подробности — Инструкция_по_работе_с_дашбордом.pdf.
3. Рабочая книга — ММНКЦ_Боткина_2025_аналитика.xlsx: 14 листов, на каждом шапка,
   автофильтр и расшифровка «факт/оценка».
4. Реестр позиций — Реестр_позиций_Боткина_2025.xlsx / .csv: построчный реестр
   профильных позиций со ссылкой на источник.
5. Методика и паспорт данных — Методика_и_паспорт_данных.pdf: источники, охват,
   классификатор, исключения, классы достоверности и ограничения.

ССЫЛКА НА ИСТОЧНИК: каждая строка реестра содержит ссылку на исходную запись ЕИС
и дату выгрузки; агрегаты отчёта и дашборда воспроизводимы из реестра.

ОГРАНИЧЕНИЯ (кратко, полный список — в методике и на экране «Методика» дашборда)
— ЕИС не публикует наименование и ИНН поставщика по договорам 223-ФЗ; для таких
  позиций поставщик указан как «не указан в ЕИС (реестр 223-ФЗ)».
— Ставка НДС и цена без НДС в реестре контрактов не публикуются и не рассчитываются.
— У части контрактов нет количества и суммы позиций: сумма распределена по цене
  контракта и помечена как «оценка».
— Страна происхождения указывается только по данным источника; догадки не используются.
— Закрытые и не подлежащие публикации закупки, а также закупки на Портале поставщиков
  Москвы в объём не входят.
— Оценочные значения (45,7 % профильных позиций) не предназначены для официальной
  отчётности.

Файлы .md — исходные тексты отчёта и инструкции (для правок), в состав передачи
входят справочно.
"""


def main() -> None:
    missing = [f for f, _ in FILES if not (OUT / f).exists()]
    if missing:
        raise SystemExit(f"Нет файлов: {missing}")

    lines = "\n".join(f"  {f:<46} — {d}" for f, d in FILES)
    readme = README.format(lines=lines)

    if ZIP_PATH.exists():
        ZIP_PATH.unlink()
    with zipfile.ZipFile(ZIP_PATH, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        z.writestr("README_Состав_передачи.txt", readme.encode("utf-8"))
        for f, _ in FILES:
            z.write(OUT / f, f)
        # исходные тексты и рисунки — справочно
        for extra in ("REPORT_Botkin_2025.md", "Инструкция_по_работе_с_дашбордом.md",
                      "Методика_и_паспорт_данных.md"):
            if (OUT / extra).exists():
                z.write(OUT / extra, extra)
        img = OUT / "img"
        if img.is_dir():
            for p in sorted(img.iterdir()):
                if p.is_file():
                    z.write(p, f"img/{p.name}")

    size = ZIP_PATH.stat().st_size / 1024 / 1024
    print(f"-> {ZIP_PATH} ({size:.1f} МБ), файлов в архиве: "
          f"{len(zipfile.ZipFile(ZIP_PATH).namelist())}")


if __name__ == "__main__":
    main()
