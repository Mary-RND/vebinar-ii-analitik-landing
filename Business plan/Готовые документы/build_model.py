def section(ws, row, text):
    ws.cell(row=row, column=1, value=text).font = SEC
    for c in range(1, 8):
        ws.cell(row=row, column=c).fill = SEC_FILL


def year_header(ws, row=7):
    ws.cell(row=row, column=1, value="Показатель").font = BOLD
    ws.cell(row=row, column=2, value="Ед.").font = BOLD
    for col, y in zip(YCOLS, YEARS):
        c = ws[f"{col}{row}"]
        c.value = y
        c.font = HDR
        c.fill = HDR_FILL
        c.alignment = Alignment(horizontal="center")


def num(ws, row, label, unit, vals, fmt="#,##0.0", bold=False, inp=False):
    ws.cell(row=row, column=1, value=label)
    ws.cell(row=row, column=2, value=unit)
    for col, v in zip(YCOLS, vals):
        c = ws[f"{col}{row}"]
        if isinstance(v, str):
            c.value = v
        else:
            c.value = v
            c.number_format = fmt
        if bold:
            c.font = BOLD
        if inp:
            c.fill = INPUT_FILL
        c.border = THIN


