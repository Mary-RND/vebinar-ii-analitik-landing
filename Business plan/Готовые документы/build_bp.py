def shade(el, hexcolor):
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    el.get_or_add_tcPr().append(shd) if el.tag.endswith("tc") else el.get_or_add_pPr().append(shd)


def para_shade(p, hexcolor):
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    p._p.get_or_add_pPr().append(shd)


def h1(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(18); p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text.upper())
    r.font.size = Pt(15); r.font.bold = True; r.font.color.rgb = PRIM
    para_shade(p, LIGHT_HEX)
    return p


def h2(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)
    r = p.add_run(text)
    r.font.size = Pt(12.5); r.font.bold = True; r.font.color.rgb = ACC
    return p


def body(text, bold=False, italic=False, size=11):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(size); r.font.bold = bold; r.font.italic = italic
    return p


def bullet(text, level=0):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.left_indent = Cm(0.6 + 0.5 * level)
    p.add_run(text)
    return p


def kpi_box(rows):
    """rows: list of (label, value) — сводная таблица-блок."""
    t = doc.add_table(rows=len(rows), cols=2)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (k, v) in enumerate(rows):
        c0, c1 = t.rows[i].cells
        c0.text = ""; c1.text = ""
        r0 = c0.paragraphs[0].add_run(k); r0.font.bold = True; r0.font.color.rgb = PRIM
        r1 = c1.paragraphs[0].add_run(v); r1.font.bold = True
        shade(c0._tc, LIGHT_HEX); shade(c1._tc, LIGHT_HEX)
        c0.width = Cm(8); c1.width = Cm(8)
    doc.add_paragraph()
    return t


def table(headers, rows, widths=None, header_hex=PRIM_HEX):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htxt in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = ""
        r = cell.paragraphs[0].add_run(htxt)
        r.font.bold = True; r.font.color.rgb = RGBColor(255, 255, 255); r.font.size = Pt(10)
        shade(cell._tc, header_hex)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            cell.text = ""
            r = cell.paragraphs[0].add_run(str(val)); r.font.size = Pt(10)
            if i % 2 == 1:
                shade(cell._tc, "F3F8FB")
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph()
    return t


